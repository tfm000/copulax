#' Draw one standalone GARCH(1, 1) residual path from a pinned spec.
#'
#' Replaces copulax/tests/_timeseries_helpers.py::simulate_garch11.
simulate_garch11_path <- function(n, omega, alpha, beta, seed) {
  spec <- ugarchspec(
    mean.model = list(armaOrder = c(0, 0), include.mean = FALSE),
    variance.model = list(model = "sGARCH", garchOrder = c(1, 1)),
    distribution.model = "norm",
    fixed.pars = list(omega = omega, alpha1 = alpha, beta1 = beta)
  )
  sim <- ugarchpath(spec, n.sim = n, n.start = N_START, m.sim = 1,
                    rseed = seed)
  y <- as.numeric(fitted(sim))
  stopifnot(length(y) == n, all(is.finite(y)))
  list(
    y = y,
    spec = sprintf(
      paste0("sGARCH(1,1) omega=%s alpha1=%s beta1=%s; ",
             "mean armaOrder=(0,0) include.mean=FALSE; ",
             "distribution=norm; ugarchpath n.sim=%d n.start=%d m.sim=1"),
      fmt_par(omega), fmt_par(alpha), fmt_par(beta), n, N_START
    )
  )
}

#' Draw one AR(1)-GARCH(1, 1) level path from a pinned spec.
#'
#' Replaces copulax/tests/_timeseries_helpers.py::simulate_ar1_garch11,
#' and also the two AR-injection loops in test_timeseries_diagnostics.py.
#' rugarch's mean equation is centred, phi(L)(y_t - mu) = eps_t, matching
#' copulax exactly.
simulate_ar1_garch11_path <- function(n, phi, mu, omega, alpha, beta, seed) {
  spec <- ugarchspec(
    mean.model = list(armaOrder = c(1, 0), include.mean = TRUE),
    variance.model = list(model = "sGARCH", garchOrder = c(1, 1)),
    distribution.model = "norm",
    fixed.pars = list(mu = mu, ar1 = phi, omega = omega,
                      alpha1 = alpha, beta1 = beta)
  )
  sim <- ugarchpath(spec, n.sim = n, n.start = N_START, m.sim = 1,
                    rseed = seed)
  y <- as.numeric(fitted(sim))
  stopifnot(length(y) == n, all(is.finite(y)))
  list(
    y = y,
    spec = sprintf(
      paste0("sGARCH(1,1) omega=%s alpha1=%s beta1=%s; ",
             "mean armaOrder=(1,0) include.mean=TRUE mu=%s ar1=%s ",
             "(centred: phi(L)(y_t - mu) = eps_t); ",
             "distribution=norm; ugarchpath n.sim=%d n.start=%d m.sim=1"),
      fmt_par(omega), fmt_par(alpha), fmt_par(beta),
      fmt_par(mu), fmt_par(phi), n, N_START
    )
  )
}

