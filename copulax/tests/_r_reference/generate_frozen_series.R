emit_case <- function(name, y, spec, seed, n) {
  cat(sprintf("    \"%s\": {\n", name))
  cat(sprintf("        \"y\": %s,\n", py_repr_list(y, 12L)))
  cat(sprintf("        \"y_bits\": %s,\n", py_repr_str_list(bits_hex(y), 12L)))
  cat("        \"provenance\": {\n")
  cat("            \"generator\": \"generate_frozen_series.R\",\n")
  cat(sprintf("            \"engine\": \"%s\",\n", ENGINE))
  cat(sprintf("            \"spec\": \"%s\",\n", spec))
  cat(sprintf("            \"seed\": %d,\n", as.integer(seed)))
  cat(sprintf("            \"n\": %d,\n", as.integer(n)))
  cat("        },\n")
  cat("    },\n")
}

