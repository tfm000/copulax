# Generate rugarch reference data for the fGARCH submodel="TGARCH" Layer-1
# tests in copulax/tests/test_timeseries_variance.py.
#
# Run from project root:
#   Rscript copulax/tests/_r_reference/generate_tgarch_fgarch_reference.R \
#       > copulax/tests/_r_reference/tgarch_fgarch_reference_data.py
#
# WHAT THIS FIXTURE IS FOR (read carefully -- the reported sigma path here is
# NOT reproduced by CopulAX's clean Zakoian recursion; see the "C-source
# finding" block below and 01-04-SUMMARY.md).
# --------------------------------------------------------------------------
# HARD-02 (TGARCH) cross-validation against rugarch's fGARCH submodel="TGARCH".
# Each case: specify a TGARCH(1,1) fGARCH spec (armaOrder=c(0,0),
# include.mean=FALSE), simulate n=2000, refit (free params), and capture:
#   * the fitted rugarch coefficients omega/alpha1/beta1/eta11,
#   * the RQ1 mapping to CopulAX convention alpha_pos = alpha*(1 - eta11),
#     alpha_neg = alpha*(1 + eta11) (beta, omega identical),
#   * the FULL reported conditional-sd path sigma(fit) (**and its square**),
#   * loglik, AIC, BIC (per-obs -> absolute via *N), standard errors,
#   * a mechanical coef(fit) check that lambda/delta are fixed at 1.
#
# RQ1 mapping (D-03 pre-approved TGARCH conform-to-literature conversion)
# ----------------------------------------------------------------------
# rugarch fGARCH (Hentschel 1995 omnibus) with submodel="TGARCH" restrictions
# lambda=delta=1, eta2=0, |eta1|<=1. CopulAX TGARCH is the Zakoian (1994)
# sigma-form with sign-split coefficients:
#   sigma_t = omega + alpha_pos*eps^+_{t-1} + alpha_neg*eps^-_{t-1} + beta*sigma_{t-1}
# Expanding alpha_pos*eps^+ + alpha_neg*eps^- with the mapping gives
#   alpha*|eps_{t-1}| - alpha*eta11*eps_{t-1}, i.e. the vignette fGARCH-TGARCH
# formula sigma_t = omega + alpha*(|eps_{t-1}| - eta11*eps_{t-1}) + beta*sigma_{t-1}.
# rugarch reports (alpha1, eta11, beta1, omega); the mapping is the sanctioned
# TGARCH conform-to-literature conversion (recorded for 01-MATH-REVIEW.md).
#
# ==========================================================================
# C-SOURCE FINDING (Option B reverse-engineering result) -- rugarch 1.5-5
# ==========================================================================
# The VIGNETTE fGARCH-TGARCH formula above (plain |eps|) does NOT reproduce
# rugarch's REPORTED sigma(fit) path at rtol<=1e-8: it diverges at ~4.2e-5
# (peak). Reverse-engineering the rugarch 1.5-5 C source
# (src/filters.c :: fgarchfilter, called by src/garchmodels.c ::
# fgarchfilterC, glued in R/rugarch-fgarch.R) reveals the reported path is
# generated by the Hentschel (1995) omnibus recursion in *standardized-z*
# space with a Box-Cox-softened absolute value:
#
#   filters.c line 162 (single-lag, kdelta=lambda=1, eta2=0 for TGARCH):
#     h[i] = omega
#          + alpha1 * ( ( sqrt(0.001^2 + (z_{i-1})^2) - eta11 * z_{i-1} )^kdelta
#                       * h_{i-1}^lambda )
#          + beta1 * h_{i-1}^lambda
#   where h == sigma (kdelta=1) and z_{i-1} = res_{i-1}/h_{i-1}.
#
# In raw-eps space this is
#   sigma_t = omega
#           + alpha1 * ( sqrt(0.001^2 * sigma_{t-1}^2 + eps_{t-1}^2)
#                        - eta11 * eps_{t-1} )
#           + beta1 * sigma_{t-1}.
# The `sqrt(0.001^2 + z^2)` softening of |z| (a fixed 1e-3 smoothing constant
# hard-coded in the C news-impact function) is the EXACT reason the vignette
# |eps| formula is ~4.2e-5 off. Confirmed empirically: this C-exact formula
# reproduces sigma(fit) to ~5.8e-16 (machine precision) on 3 seeds; the
# vignette |eps| formula peaks at 4.2e-5.
#
# Pre-sample (fgarchfilterC lines 254-262): h[i] = hEst for i in 0..m-1, where
# hEst = mvar = mean(|res[1:n]|)^lambda ^ (1/lambda) = mean(|res|) for TGARCH
# (R/rugarch-fgarch.R line 283, rec.init type==1 "all"). eta1 default 0.05 and
# submodel fixing (lambda=1, delta=1, eta2=0, fk=0 => kdelta=1) are set in
# R/rugarch-startpars.R :: .fgarchModel("TGARCH").
#
# CONSEQUENCE FOR THE LAYER-1 GATE: CopulAX's PRODUCTION TGARCH recursion is
# the clean Zakoian |eps| form (no 0.001 softening) and must NOT be changed to
# mimic rugarch (project decision). So CopulAX's Zakoian
# recursion at the mapped params does NOT match rugarch's reported sigma at
# 1e-8 (measured ~4.2e-5 with the pre-sample matched). The co-located
# reference module reproduces the C-exact formula and DEMONSTRATES it matches
# rugarch at 1e-8, and documents the divergence from CopulAX's Zakoian form.
# The Zakoian production recursion is instead validated as a Layer-1 gate
# against the `arch` TARCH/ZARCH (power=1, o=1) oracle -- see 01-04-SUMMARY.md
# (Option A) once the user selects the resolution.
#
# Residual laws (copulax <-> rugarch): normal <-> norm, student_t <-> std.

