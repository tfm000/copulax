# ---------------------------------------------------------------------
# Python-repr helpers (identical convention to
# generate_garch_standalone_reference.R).
# ---------------------------------------------------------------------
py_repr_scalar <- function(x) {
  if (is.logical(x)) return(if (x) "True" else "False")
  if (is.character(x)) return(sprintf("\"%s\"", x))
  if (is.na(x) || is.nan(x)) return("float('nan')")
  if (is.infinite(x)) return(if (x > 0) "float('inf')" else "float('-inf')")
  sprintf("%.17g", x)
}

py_repr_array <- function(x) {
  if (length(x) == 0) return("np.array([], dtype=float)")
  body <- paste(sapply(x, py_repr_scalar), collapse=", ")
  sprintf("np.array([%s], dtype=float)", body)
}

py_repr_tuple <- function(x) {
  if (length(x) == 0) return("()")
  body <- paste(sapply(x, py_repr_scalar), collapse=", ")
  if (length(x) == 1) sprintf("(%s,)", body) else sprintf("(%s)", body)
}

cx_residual_name <- function(rugarch_name) {
  switch(rugarch_name,
    "norm" = "normal",
    "std"  = "student_t",
    stop("cx_residual_name: unsupported ", rugarch_name)
  )
}

# ---------------------------------------------------------------------
# Per-case driver
# ---------------------------------------------------------------------
process_case <- function(label, residual_dist, fixed_pars, residual_shape_truth,
                         n_sim = 2000, seed = 77) {
  vlist <- list(model="fGARCH", submodel="TGARCH", garchOrder=c(1, 1))
  spec_truth <- ugarchspec(
    mean.model=list(armaOrder=c(0,0), include.mean=FALSE),
    variance.model=vlist,
    distribution.model=residual_dist,
    fixed.pars=fixed_pars
  )
  sim <- ugarchpath(spec_truth, n.sim=n_sim, m.sim=1, rseed=seed)
  y <- as.numeric(fitted(sim))
  spec <- ugarchspec(
    mean.model=list(armaOrder=c(0,0), include.mean=FALSE),
    variance.model=vlist,
    distribution.model=residual_dist
  )
  fit <- ugarchfit(spec=spec, data=y, solver="hybrid")
  cf <- coef(fit)

  # --- A1 mechanical check: lambda / delta must NOT be free in coef(fit). ---
  # For the named submodel rugarch fixes them (they never appear in coef());
  # if either appears, the fixture is invalid -- fail loudly (no silent failures).
  cf_names <- names(cf)
  if (any(cf_names == "lambda") || any(cf_names == "delta")) {
    stop(sprintf(
      "A1 violation for %s: lambda/delta appear as FREE params in coef(): %s",
      label, paste(cf_names, collapse=", ")))
  }
  # Positive confirmation from the spec's fixed fmodel parameters.
  fm <- spec@model$fmodel$fpars
  if (fm$lambda != 1 || fm$delta != 1 || fm$eta2 != 0 || fm$fk != 0) {
    stop(sprintf(
      "A1 violation for %s: TGARCH submodel expected lambda=delta=1, eta2=fk=0; got lambda=%g delta=%g eta2=%g fk=%g",
      label, fm$lambda, fm$delta, fm$eta2, fm$fk))
  }

  mc <- fit@fit$matcoef
  se <- mc[, 2]; names(se) <- rownames(mc)
  ll <- as.numeric(fit@fit$LLH)
  N <- length(y)
  ic <- infocriteria(fit)
  aic_total <- as.numeric(ic[1, 1]) * N
  bic_total <- as.numeric(ic[2, 1]) * N
  sig <- as.numeric(sigma(fit))
  res <- as.numeric(residuals(fit))
  # rugarch's reported UNCONDITIONAL variance for the fGARCH-TGARCH fit.
  # IMPORTANT (VERIFIED empirically, 01-MATH-REVIEW.md unconditional-
  # variance third-party section): uncvariance is a CLOSED-FORM accessor
  # derived from the fitted coefficients, NOT from the 0.001-softened
  # reported sigma path. It equals (omega/(1 - persistence))^2 with the
  # SAME first-moment persistence copulax's clean Zakoian form uses
  # (alpha_pos*E[z+] + alpha_neg*E[z-] + beta) -- so the 0.001 news-impact
  # softening (which perturbs sigma(fit) at O(1e-5), finding 1) does NOT
  # enter uncvariance. copulax's Zakoian stats()["unconditional_variance"]
  # (== unconditional_sigma^2) therefore matches this TIGHTLY, not at the
  # softening-widened tolerance. Captured as the third-party oracle.
  uncvar <- tryCatch(uncvariance(fit),
                     error = function(e) NA_real_)

  omega  <- unname(cf["omega"])
  alpha1 <- unname(cf["alpha1"])
  beta1  <- unname(cf["beta1"])
  eta11  <- unname(cf["eta11"])

  # RQ1 mapping -> CopulAX (alpha_pos / alpha_neg) convention.
  alpha_pos <- alpha1 * (1 - eta11)
  alpha_neg <- alpha1 * (1 + eta11)

  # Pre-sample warm value rugarch actually uses for TGARCH (lambda=1):
  # mvar = mean(|res[1:N]|).  rec.init="all" (type==1) uses the whole window.
  pre_sample_sigma <- mean(abs(res))

  # SEs: rugarch reports SE(alpha1), SE(eta11); the SE of the derived
  # alpha_pos/alpha_neg is a linear combination we do NOT emit (the CopulAX
  # test compares its on-basis SE separately).  We emit rugarch's native SEs.
  list(
    label                = label,
    residual_dist        = cx_residual_name(residual_dist),
    residual_shape_truth = residual_shape_truth,
    y                    = y,
    # rugarch-native fitted params (for provenance / C-exact reference).
    rugarch_params       = list(omega=omega, alpha1=alpha1, beta1=beta1, eta11=eta11),
    # CopulAX-convention mapped params.
    params               = list(omega=omega, alpha_pos=alpha_pos,
                                alpha_neg=alpha_neg, beta=beta1),
    residual             = switch(residual_dist,
                                  "norm" = list(),
                                  "std"  = list(nu = unname(cf["shape"]))),
    standard_errors      = list(omega=unname(se["omega"]),
                                alpha1=unname(se["alpha1"]),
                                beta1=unname(se["beta1"]),
                                eta11=unname(se["eta11"])),
    residual_se          = switch(residual_dist,
                                  "norm" = list(),
                                  "std"  = list(nu = unname(se["shape"]))),
    loglikelihood        = ll,
    aic                  = aic_total,
    bic                  = bic_total,
    sigma                = sig,
    sigma2               = sig^2,
    pre_sample_sigma     = pre_sample_sigma,
    uncvariance          = uncvar
  )
}

